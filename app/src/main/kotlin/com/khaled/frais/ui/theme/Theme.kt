val AppShapes = Shapes(
    extraSmall = RoundedCornerShape(2.dp),
    small = RoundedCornerShape(4.dp),
    medium = RoundedCornerShape(8.dp),
    large = RoundedCornerShape(12.dp),
    extraLarge = RoundedCornerShape(16.dp)
)

@Composable
fun AppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    appTheme: String = com.khaled.frais.app.FraisData.appTheme,
    @Suppress("UNUSED_PARAMETER") dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val isDark = when (appTheme) {
        com.khaled.frais.app.FraisData.THEME_LIGHT -> false
        com.khaled.frais.app.FraisData.THEME_DARK, com.khaled.frais.app.FraisData.THEME_AMOLED -> true
        else -> darkTheme
    }

    val colorScheme = when {
        appTheme == com.khaled.frais.app.FraisData.THEME_AMOLED -> amoledScheme
        isDark -> darkScheme
        else -> lightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content
    )
}
